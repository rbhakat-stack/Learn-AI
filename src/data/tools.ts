/** Group tools by category for fast UI access. */
export function groupToolsByCategory(tools: Tool[] = TOOLS) {
  return tools.reduce<Record<string, Tool[]>>((acc, t) => {
    (acc[t.category] ??= []).push(t);
    return acc;
  }, {});
}

export function findTool(slug: string) {
  return TOOLS.find((t) => t.slug === slug);
}
